parts = gl["parts"]
pts, miss = [], []
for z in zones:
    for o in z["objects"]:
        if o["char"] not in parts:
            miss.append(o["char"])
        pts.append((o["char"], o["x"], o["y"], o["r"]))
chars = [p[0] for p in pts]

print("区块 %d 个，实物 %d 个" % (len(zones), len(pts)))
print("缺字形  : %s" % ("、".join(miss) if miss else "无 ✓"))
